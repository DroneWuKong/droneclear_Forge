export default {
  async fetch(request, env) {
    if (request.method === 'OPTIONS') {
      return new Response(null, { status: 204, headers: CORS });
    }

    const url = new URL(request.url);
    const type = url.searchParams.get('type') || '';

    if (request.method === 'POST') {
      const adminKey = env.FORGE_BLOBS_ADMIN_KEY;
      const provided = (
        request.headers.get('authorization') || ''
      ).replace(/^Bearer\s+/i, '');

      if (!adminKey) {
        return resp(
          { error: 'FORGE_BLOBS_ADMIN_KEY not configured' },
          503,
        );
      }
      if (provided !== adminKey) {
        return resp({ error: 'Invalid admin key' }, 401);
      }
      if (!type || !DATASETS.has(type)) {
        return resp({ error: `Unknown dataset: ${type}` }, 404);
      }

      try {
        const body = await request.text();
        if (!body || body.length < 2) {
          return resp({ error: 'Empty body' }, 400);
        }

        let parsed;
        try {
          parsed = JSON.parse(body);
        } catch (error) {
          return resp(
            {
              error:
                'Invalid JSON: ' +
                (error instanceof Error ? error.message : String(error)),
            },
            400,
          );
        }

        const freshness = freshnessOf(parsed, type, 'admin-write');
        if (
          FRESHNESS_LIMIT_MS.has(type) &&
          freshness.generated_at == null
        ) {
          return resp(
            {
              error:
                `Dataset ${type} requires a valid meta.generated_at timestamp`,
              freshness,
            },
            400,
          );
        }

        // Semantic controls are also checked before accepting a current public
        // artifact into KV; a successful write means projections can be made
        // from the stored document without weakening the publication contract.
        try {
          projectDataset(parsed, type, new URLSearchParams({ view: 'method' }));
        } catch (error) {
          if (error && error.code === 'DATASET_PUBLICATION_CONTROL') {
            return resp(
              {
                error: `Dataset ${type} failed semantic publication controls`,
                validation_errors: error.validationErrors || [],
              },
              400,
            );
          }
          throw error;
        }

        const kv = PIE_OUTPUTS_KEYS.has(type)
          ? env.PIE_OUTPUTS
          : env.PIE_DB;
        await kv.put(type, body);

        return resp({
          ok: true,
          type,
          size: body.length,
          freshness,
          message: `${type} written to KV (${body.length} bytes)`,
        });
      } catch (error) {
        return resp(
          {
            error:
              'KV write failed: ' +
              (error instanceof Error ? error.message : String(error)),
          },
          500,
        );
      }
    }

    if (!type) {
      return resp(
        {
          error: 'type parameter required',
          available: Array.from(DATASETS),
        },
        400,
      );
    }
    if (!DATASETS.has(type)) {
      return resp({ error: `Unknown dataset: ${type}` }, 404);
    }

    try {
      const kv = PIE_OUTPUTS_KEYS.has(type)
        ? env.PIE_OUTPUTS
        : env.PIE_DB;
      const raw = await kv.get(type);
      if (raw) {
        return parseAndServe(raw, type, 'kv', url.searchParams);
      }
    } catch (error) {
      console.error(
        `[forge-data] KV error for ${type}:`,
        error instanceof Error ? error.message : String(error),
      );
    }

    // Static fallback is useful for availability, but the same freshness and
    // semantic gates apply. Old or unsafe bundled JSON is never silently
    // labeled current.
    try {
      for (const tryPath of [
        `/${type}.json`,
        `/static/${type}.json`,
      ]) {
        try {
          const staticUrl = new URL(request.url);
          staticUrl.pathname = tryPath;
          staticUrl.search = '';
          const staticResponse = await env.ASSETS.fetch(
            new Request(staticUrl.toString()),
          );
          if (staticResponse.ok) {
            const raw = await staticResponse.text();
            return parseAndServe(
              raw,
              type,
              `static:${tryPath}`,
              url.searchParams,
            );
          }
        } catch {
          // Try the next static path.
        }
      }
    } catch {
      // ASSETS may be absent in local worker tests.
    }

    return resp(
      { error: `Dataset ${type} not available`, type },
      404,
    );
  },
};
