const DEFAULT_EVENT_LIMIT = 20;
const MAX_EVENT_LIMIT = 100;
const DEFAULT_SOURCE_LIMIT = 50;
const MAX_SOURCE_LIMIT = 200;
const MAX_REPORTING_SPAN_DAYS = 5.01;
const MAX_EVENT_SPAN_DAYS = 3.01;
const MAX_REPORTING_CLUSTER_ARTICLES = 250;
const MAX_EVENT_CLUSTER_ARTICLES = 400;

function integerParam(params, name, fallback, minimum, maximum) {
  const raw = params && typeof params.get === 'function' ? params.get(name) : null;
  const parsed = Number.parseInt(raw || '', 10);
  if (!Number.isFinite(parsed)) return fallback;
  return Math.max(minimum, Math.min(maximum, parsed));
}

function normalized(value) {
  return String(value || '').trim();
}

function normalizedActor(value) {
  return normalized(value);
}

function finiteNumber(value) {
  const parsed = Number(value);
  return Number.isFinite(parsed) ? parsed : 0;
}

function eventDateValue(event) {
  const raw = event && (event.publication_end || event.publication_start);
  const parsed = Date.parse(raw || '');
  return Number.isFinite(parsed) ? parsed : 0;
}

function sortEventsNewestFirst(events) {
  return [...events].sort((left, right) => {
    const dateDifference = eventDateValue(right) - eventDateValue(left);
    if (dateDifference) return dateDifference;
    return String(left.candidate_event_id || '').localeCompare(
      String(right.candidate_event_id || ''),
    );
  });
}

export function articleEventPublicationErrors(data) {
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    return ['event artifact must be a JSON object'];
  }
  const meta = data.meta && typeof data.meta === 'object' ? data.meta : {};
  const controls =
    meta.quality_controls && typeof meta.quality_controls === 'object'
      ? meta.quality_controls
      : {};
  const errors = [];
  if (String(meta.version || '') !== '1.1') {
    errors.push(`event artifact version must be 1.1; got ${String(meta.version || 'missing')}`);
  }
  if (
    String(meta.generator || '') !==
    'services/pipeline/article_event_clusters_quality.py'
  ) {
    errors.push('event artifact was not generated by the hardened quality path');
  }
  if (controls.shared_url_requires_title_and_time_agreement !== true) {
    errors.push('shared-URL title/time agreement control is missing');
  }
  if (
    controls.same_source_shared_url_different_title_merge_allowed !== false
  ) {
    errors.push('same-source rolling-URL control is missing');
  }
  if (controls.same_single_source_candidate_pair_allowed !== false) {
    errors.push('same-source candidate-event control is missing');
  }
  if (
    finiteNumber(controls.largest_serialized_reporting_cluster_span_days) >
    MAX_REPORTING_SPAN_DAYS
  ) {
    errors.push('a reporting cluster exceeds the five-day publication ceiling');
  }
  if (
    finiteNumber(controls.largest_serialized_candidate_event_span_days) >
    MAX_EVENT_SPAN_DAYS
  ) {
    errors.push('a candidate event exceeds the three-day publication ceiling');
  }
  if (
    finiteNumber(controls.largest_serialized_reporting_cluster_articles) >
    MAX_REPORTING_CLUSTER_ARTICLES
  ) {
    errors.push('a reporting cluster exceeds the article-count ceiling');
  }
  if (
    finiteNumber(controls.largest_serialized_candidate_event_articles) >
    MAX_EVENT_CLUSTER_ARTICLES
  ) {
    errors.push('a candidate event exceeds the article-count ceiling');
  }
  if (!Array.isArray(data.actor_summary)) {
    errors.push('event artifact actor_summary must be a list');
  }
  if (!Array.isArray(data.candidate_events)) {
    errors.push('event artifact candidate_events must be a list');
  }
  return errors;
}

export function sourceCoveragePublicationErrors(data) {
  if (!data || typeof data !== 'object' || Array.isArray(data)) {
    return ['source coverage artifact must be a JSON object'];
  }
  const meta = data.meta && typeof data.meta === 'object' ? data.meta : {};
  const sources = Array.isArray(data.sources) ? data.sources : null;
  const coverage = data.coverage && typeof data.coverage === 'object' ? data.coverage : null;
  const gaps = data.gaps && typeof data.gaps === 'object' ? data.gaps : null;
  const errors = [];
  if (String(meta.version || '') !== '1.0') {
    errors.push(`coverage artifact version must be 1.0; got ${String(meta.version || 'missing')}`);
  }
  if (
    String(meta.generator || '') !==
    'services/pipeline/source_coverage_matrix.py'
  ) {
    errors.push('coverage artifact was not generated by the validated coverage pipeline');
  }
  if (meta.event_artifact_used !== true) {
    errors.push('publication-safe candidate-event evidence was not used');
  }
  if (!sources || !sources.length) {
    errors.push('source coverage matrix must contain a non-empty sources list');
  }
  if (!coverage) errors.push('source coverage artifact lacks a coverage object');
  if (!gaps) errors.push('source coverage artifact lacks a gaps object');
  const expected = finiteNumber(meta.analyzed_article_records);
  if (expected < 1) errors.push('analyzed article count must be positive');
  if (sources) {
    const ids = sources.map((row) => normalized(row && row.source_key)).filter(Boolean);
    if (new Set(ids).size !== ids.length) errors.push('source keys are not unique');
    const actual = sources.reduce(
      (total, row) => total + finiteNumber(row && row.article_count),
      0,
    );
    if (actual !== expected) {
      errors.push(`per-source article counts sum to ${actual}, expected ${expected}`);
    }
  }
  const concentration =
    meta.source_concentration && typeof meta.source_concentration === 'object'
      ? meta.source_concentration
      : {};
  for (const field of ['top_source_share', 'top_five_source_share']) {
    const value = finiteNumber(concentration[field]);
    if (value < 0 || value > 1) errors.push(`${field} must be between zero and one`);
  }
  const start = Date.parse(meta.coverage_start || '');
  const end = Date.parse(meta.coverage_end || '');
  if (Number.isFinite(start) && Number.isFinite(end) && start > end) {
    errors.push('coverage start is after coverage end');
  }
  return errors;
}

export function validateDatasetForPublication(data, type) {
  if (type === 'article_event_clusters') {
    return articleEventPublicationErrors(data);
  }
  if (type === 'source_coverage_matrix') {
    return sourceCoveragePublicationErrors(data);
  }
  return [];
}

export function projectArticleEventClusters(data, params) {
  if (!data || typeof data !== 'object' || Array.isArray(data)) return data;

  const actor = normalizedActor(params && params.get ? params.get('actor') : '');
  const eventId = normalized(params && params.get ? params.get('event_id') : '');
  const view = normalized(params && params.get ? params.get('view') : '').toLowerCase();
  const meta = data.meta && typeof data.meta === 'object' ? data.meta : {};
  const summaries = Array.isArray(data.actor_summary) ? data.actor_summary : [];
  const events = Array.isArray(data.candidate_events) ? data.candidate_events : [];

  if (eventId) {
    const event = events.find(
      (row) => row && row.candidate_event_id === eventId,
    ) || null;
    return {
      meta,
      candidate_event: event,
      query: {
        event_id: eventId,
        found: Boolean(event),
      },
    };
  }

  if (actor) {
    const offset = integerParam(params, 'offset', 0, 0, Number.MAX_SAFE_INTEGER);
    const limit = integerParam(
      params,
      'limit',
      DEFAULT_EVENT_LIMIT,
      1,
      MAX_EVENT_LIMIT,
    );
    const matching = sortEventsNewestFirst(
      events.filter(
        (event) =>
          event &&
          Array.isArray(event.actors_mentioned) &&
          event.actors_mentioned.includes(actor),
      ),
    );
    const summary = summaries.find(
      (row) => row && row.actor === actor,
    ) || null;
    return {
      meta,
      actor_summary: summary ? [summary] : [],
      candidate_events: matching.slice(offset, offset + limit),
      query: {
        actor,
        offset,
        limit,
        returned_event_count: Math.max(
          0,
          Math.min(limit, matching.length - offset),
        ),
        total_candidate_event_count: matching.length,
        has_more: offset + limit < matching.length,
      },
    };
  }

  if (view === 'summary') {
    return {
      meta,
      actor_summary: summaries,
      query: {
        view: 'summary',
        candidate_event_count:
          Number(meta.candidate_event_cluster_count) || events.length,
        serialized_candidate_event_count: events.length,
      },
    };
  }

  if (view === 'method') {
    return {
      meta,
      query: { view: 'method' },
    };
  }

  return data;
}

function sourceHealthStatus(row) {
  return normalized(row && row.collector_health && row.collector_health.status) || 'unknown';
}

function sourceSearchText(row) {
  const aliases = Array.isArray(row && row.observed_aliases)
    ? row.observed_aliases.map((item) => normalized(item && item.value)).join(' ')
    : '';
  return [
    row && row.source_key,
    row && row.display_name,
    row && row.category,
    row && row.vertical,
    row && row.registered_geo,
    row && row.registered_url,
    aliases,
  ].map(normalized).join(' ').toLowerCase();
}

function sortCoverageSources(rows, sort) {
  return [...rows].sort((left, right) => {
    if (sort === 'name') {
      return normalized(left.display_name || left.source_key).localeCompare(
        normalized(right.display_name || right.source_key),
      );
    }
    if (sort === 'recent') {
      const leftDate = Date.parse(left.coverage_end || '') || 0;
      const rightDate = Date.parse(right.coverage_end || '') || 0;
      return rightDate - leftDate || finiteNumber(right.article_count) - finiteNumber(left.article_count);
    }
    if (sort === 'events') {
      return finiteNumber(right.candidate_event_count) - finiteNumber(left.candidate_event_count)
        || finiteNumber(right.article_count) - finiteNumber(left.article_count);
    }
    return finiteNumber(right.article_count) - finiteNumber(left.article_count)
      || normalized(left.source_key).localeCompare(normalized(right.source_key));
  });
}

export function projectSourceCoverage(data, params) {
  if (!data || typeof data !== 'object' || Array.isArray(data)) return data;
  const view = normalized(params && params.get ? params.get('view') : '').toLowerCase();
  const sourceKey = normalized(params && params.get ? params.get('source') : '');
  const meta = data.meta && typeof data.meta === 'object' ? data.meta : {};
  const sources = Array.isArray(data.sources) ? data.sources : [];

  if (sourceKey) {
    const source = sources.find((row) => row && row.source_key === sourceKey) || null;
    return {
      meta,
      source,
      query: { source: sourceKey, found: Boolean(source) },
    };
  }

  if (view === 'summary') {
    return {
      meta,
      coverage: data.coverage || {},
      gaps: data.gaps || {},
      alerts: Array.isArray(data.alerts) ? data.alerts : [],
      query: {
        view: 'summary',
        source_count: sources.length,
      },
    };
  }

  if (view === 'sources') {
    const query = normalized(params && params.get ? params.get('q') : '').toLowerCase();
    const registration = normalized(
      params && params.get ? params.get('registration') : '',
    ).toLowerCase();
    const health = normalized(params && params.get ? params.get('health') : '').toLowerCase();
    const activity = normalized(params && params.get ? params.get('activity') : '').toLowerCase();
    const sort = normalized(params && params.get ? params.get('sort') : 'articles').toLowerCase();
    const offset = integerParam(params, 'offset', 0, 0, Number.MAX_SAFE_INTEGER);
    const limit = integerParam(
      params,
      'limit',
      DEFAULT_SOURCE_LIMIT,
      1,
      MAX_SOURCE_LIMIT,
    );
    const matching = sortCoverageSources(
      sources.filter((row) => {
        if (!row || typeof row !== 'object') return false;
        if (query && !sourceSearchText(row).includes(query)) return false;
        if (registration === 'registered' && row.registered !== true) return false;
        if (registration === 'unregistered' && row.registered !== false) return false;
        if (health && sourceHealthStatus(row) !== health) return false;
        if (activity === 'observed' && finiteNumber(row.article_count) < 1) return false;
        if (activity === 'no-articles' && finiteNumber(row.article_count) > 0) return false;
        if (activity === 'events' && finiteNumber(row.candidate_event_count) < 1) return false;
        return true;
      }),
      sort,
    );
    return {
      meta,
      sources: matching.slice(offset, offset + limit),
      query: {
        view: 'sources',
        q: query,
        registration,
        health,
        activity,
        sort,
        offset,
        limit,
        returned_source_count: Math.max(
          0,
          Math.min(limit, matching.length - offset),
        ),
        total_source_count: matching.length,
        has_more: offset + limit < matching.length,
      },
    };
  }

  return data;
}

export function projectDataset(data, type, params) {
  const errors = validateDatasetForPublication(data, type);
  if (errors.length) {
    const error = new Error(
      `Dataset ${type} failed publication controls: ${errors.join('; ')}`,
    );
    error.code = 'DATASET_PUBLICATION_CONTROL';
    error.validationErrors = errors;
    throw error;
  }
  if (type === 'article_event_clusters') {
    return projectArticleEventClusters(data, params);
  }
  if (type === 'source_coverage_matrix') {
    return projectSourceCoverage(data, params);
  }
  return data;
}

